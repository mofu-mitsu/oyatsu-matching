/**
 * 診断の回答（Sweet, Tender, Fresh, Japaneseのスコア）から16タイプのコードを算出する
 */
export function calculateSnackType(
  sweetScore: number, // 0..100 (>50 = Sweet(S), <=50 = Salty(Y))
  tenderScore: number, // 0..100 (>50 = Tender(T), <=50 = Hard(H))
  freshScore: number, // 0..100 (>50 = Chilled(C), <=50 = Fresh(F)) -- Note: ユーザー視点「常温・焼き菓子(0)」vs「ひんやり(100)」
  japaneseScore: number // 0..100 (>50 = Western(W), <=50 = Japanese(J))
): SnackTypeInfo {
  const s = sweetScore > 50 ? 'S' : 'Y';
  const t = tenderScore > 50 ? 'T' : 'H';
  const f = freshScore > 50 ? 'C' : 'F'; // 50超ならChilled(C), 以下ならFresh(F)
  const j = japaneseScore > 50 ? 'W' : 'J'; // 50超ならWestern(W), 以下ならJapanese(J)

  const code = `${s}${t}${f}${j}`;
  return SNACK_TYPES[code] || SNACK_TYPES.STFW;
}
